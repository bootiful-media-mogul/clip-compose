// where the app finds mogul and auth0. these come from local.properties (not checked in)
// or -P on the command line; with no auth0 client id, the app runs against a demo mogul
val localProperties = Properties().apply {
    rootProject.file("local.properties").takeIf { it.exists() }?.inputStream()?.use { load(it) }
}

fun mogulProperty(name: String, default: String = ""): String =
    providers.gradleProperty(name).orNull ?: localProperties.getProperty(name) ?: default

val auth0Domain = mogulProperty("mogul.auth0.domain").let { if (it.isEmpty() || it.endsWith("/")) it else "$it/" }

val mogulConfig = mapOf(
    // the gateway, as this machine sees it: the ios simulator shares this machine's network,
    // and the android emulator reaches it at 10.0.2.2 instead (see AndroidMogul)
    "server" to mogulProperty("mogul.server", "http://127.0.0.1:1010"),
    "auth0Domain" to auth0Domain,
    "auth0ClientId" to mogulProperty("mogul.auth0.clientId"),
    // the auth0 api that stands for mogul's api; the api and the gateway check tokens are for it
    "auth0Audience" to mogulProperty("mogul.auth0.audience", "https://api.mogul.tools"),
    "redirectUri" to mogulProperty("mogul.redirectUri", "com.joshlong.mogul://callback"),
)

val generateMogulConfig = tasks.register("generateMogulConfig") {
    val values = mogulConfig
    val output = layout.buildDirectory.dir("generated/mogul-config/kotlin")
    inputs.properties(values)
    outputs.dir(output)
    doLast {
        fun quoted(value: String) = "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
        val file = output.get().file("com/joshlong/mogul/MogulConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(buildString {
            appendLine("// generated by the generateMogulConfig task in shared/build.gradle.kts. don't edit")
            appendLine("package com.joshlong.mogul")
            appendLine()
            appendLine("internal val mogulConfig = MogulConfig(")
            for ((name, value) in values) appendLine("    $name = ${quoted(value)},")
            appendLine(")")
        })
    }
}

