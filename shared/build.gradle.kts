// oidc-appsupport's manifest needs the scheme auth0 redirects back to; the app sets it for
// real (androidApp/build.gradle.kts), this is so the library's own host tests build
androidComponents {
    onVariants { variant ->
        val scheme = mogulConfig.getValue("redirectUri").substringBefore(":")
        variant.manifestPlaceholders.put("oidcRedirectScheme", scheme)
        (variant as? com.android.build.api.variant.HasHostTests)?.hostTests?.values?.forEach {
            it.manifestPlaceholders.put("oidcRedirectScheme", scheme)
        }
    }
}